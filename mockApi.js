// Generate historical data for charts
function generateOwidData(iso) {
  const country = mockCountries.find(c => 
    c.iso?.toUpperCase() === iso?.toUpperCase() || 
    c.ThreeLetterSymbol?.toUpperCase() === iso?.toUpperCase()
  );
  
  if (!country) return [];
  
  const totalCases = country.TotalCases || 0;
  const totalDeaths = country.TotalDeaths || 0;
  const data = [];
  const today = new Date('2024-04-13');
  
  // Generate 6 months of historical data (every 3 days)
  for (let i = 180; i >= 0; i -= 3) {
    const date = new Date(today);
    date.setDate(date.getDate() - i);
    const progress = 1 - (i / 180);
    
    data.push({
      date: date.toISOString().split('T')[0],
      total_cases: Math.round(totalCases * (0.5 + 0.5 * progress)),
      new_cases: Math.round(Math.random() * 1000),
      total_deaths: Math.round(totalDeaths * (0.5 + 0.5 * progress)),
      new_deaths: Math.round(Math.random() * 50),
      iso_code: iso.toUpperCase()
    });
  }
  return data;
}

